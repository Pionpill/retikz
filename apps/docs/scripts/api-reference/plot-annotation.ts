import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { createMergedReferenceMdx, splitReferenceSections } from './merged-reference';
import { assertPlotAnnotationTranslated, translatePlotAnnotation } from './plot-annotation.en';
import { annotationDescriptions } from './plot-annotation.schema';
import { createApiReferenceMdx } from './tex';

const root = path.resolve(import.meta.dirname, '../../../..');
const owner = 'viz/plot/mark/annotation';

/** 生成三类标注的公开 Props、Source 类型及同源 Schema 参考 */
export const writePlotAnnotationApiReferenceMdx = async (): Promise<void> => {
  const contents = path.join(root, 'apps/docs/src/modules/docs/contents');
  const output = path.join(contents, owner, '_includes');
  mkdirSync(output, { recursive: true });
  for (const lang of ['zh', 'en'] as const) {
    const props = await createApiReferenceMdx(
      {
        packageName: '@retikz/plot-react',
        packageDirectory: 'packages/viz/plot-react',
        tsconfigPath: path.join(root, 'packages/viz/plot-react/tsconfig.json'),
        translate: translatePlotAnnotation,
        resolveSchemaLocalization: schema => ({
          descriptions: Object.fromEntries(
            Object.keys(schema.shape)
              .filter(key => annotationDescriptions[key] !== undefined)
              .map(key => [key, annotationDescriptions[key]!]),
          ),
        }),
        entries: [
          {
            source: path.join(root, 'packages/viz/plot-react/src/index.ts'),
            title: { zh: '标注属性', en: 'Annotation properties' },
            symbols: ['PointAnnotationProps', 'PathAnnotationProps', 'IntervalAnnotationProps'],
            fullMemberSymbols: ['PointAnnotationProps', 'PathAnnotationProps', 'IntervalAnnotationProps'],
          },
        ],
      },
      lang,
    );
    const symbols = ['IRPlotPointAnnotation', 'IRPlotPathAnnotation', 'IRPlotIntervalAnnotation'];
    const ir = await createApiReferenceMdx(
      {
        packageName: '@retikz/plot',
        packageDirectory: 'packages/viz/plot',
        tsconfigPath: path.join(root, 'packages/viz/plot/tsconfig.json'),
        translate: translatePlotAnnotation,
        entries: [
          {
            source: path.join(root, 'packages/viz/plot/src/index.ts'),
            title: { zh: 'Source IR', en: 'Source IR' },
            symbols,
            declarationOnlySymbols: symbols,
          },
        ],
      },
      lang,
    );
    if (lang === 'en') assertPlotAnnotationTranslated();
    const reference = readFileSync(path.join(contents, `viz/plot/reference/mark/index.${lang}.mdx`), 'utf8');
    const sections = splitReferenceSections(reference, '2,3');
    const schemas = ['PointAnnotationSchema', 'PathAnnotationSchema', 'IntervalAnnotationSchema']
      .map(name => {
        const section = sections.find(item => item.name === name);
        if (!section) throw new Error(`Missing ${name} reference`);
        return `## ${name}\n\n${section.body}`;
      })
      .join('\n\n');
    const merged = createMergedReferenceMdx(`${props}\n\n${ir}`, schemas, owner, lang, true);
    writeFileSync(
      path.join(output, `generated.${lang}.mdx`),
      `{/* Generated by scripts/generate-plot-annotation-api-reference.ts. Do not edit manually. */}\n\n${merged}\n`,
      'utf8',
    );
  }
};
