import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { createMergedReferenceMdx, splitReferenceSections } from './merged-reference';
import { assertPlotPointTranslated, translatePlotPoint } from './plot-point.en';
import { createApiReferenceMdx } from './tex';
import type { ApiReferencePackageConfig } from './tex';

const root = path.resolve(import.meta.dirname, '../../../..');
const owner = 'viz/plot/mark/point';

/** 从 React 公开入口读取散点属性，复用图元契约页的 Schema 说明 */
export const writePlotPointApiReferenceMdx = async (): Promise<void> => {
  const config: ApiReferencePackageConfig = {
    packageName: '@retikz/plot-react',
    packageDirectory: 'packages/viz/plot-react',
    tsconfigPath: path.join(root, 'packages/viz/plot-react/tsconfig.json'),
    translate: translatePlotPoint,
    entries: [
      {
        source: path.join(root, 'packages/viz/plot-react/src/index.ts'),
        title: { zh: '散点属性', en: 'Point properties' },
        symbols: ['PointMarkProps'],
      },
    ],
  };
  const contents = path.join(root, 'apps/docs/src/modules/docs/contents');
  const output = path.join(contents, owner, '_includes');
  mkdirSync(output, { recursive: true });
  for (const lang of ['zh', 'en'] as const) {
    const props = await createApiReferenceMdx(config, lang);
    const ir = await createApiReferenceMdx(
      {
        packageName: '@retikz/plot',
        packageDirectory: 'packages/viz/plot',
        tsconfigPath: path.join(root, 'packages/viz/plot/tsconfig.json'),
        translate: translatePlotPoint,
        entries: [
          {
            source: path.join(root, 'packages/viz/plot/src/index.ts'),
            title: { zh: 'Source IR', en: 'Source IR' },
            symbols: ['IRPlotPointMark'],
            declarationOnlySymbols: ['IRPlotPointMark'],
          },
        ],
      },
      lang,
    );
    const source = `${props}\n\n${ir}`;
    if (lang === 'en') assertPlotPointTranslated();
    const reference = readFileSync(path.join(contents, `viz/plot/reference/mark/index.${lang}.mdx`), 'utf8');
    const pointSchema = splitReferenceSections(reference, '2,3').find(section => section.name === 'PointMarkSchema');
    if (!pointSchema) throw new Error('Missing PointMarkSchema reference');
    const merged = createMergedReferenceMdx(source, `## PointMarkSchema\n\n${pointSchema.body}`, owner, lang, true);
    writeFileSync(
      path.join(output, `generated.${lang}.mdx`),
      `{/* Generated by scripts/generate-plot-point-api-reference.ts. Do not edit manually. */}\n\n${merged}\n`,
      'utf8',
    );
  }
};
