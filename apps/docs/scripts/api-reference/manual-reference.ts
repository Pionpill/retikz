import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { manualReferencePages } from './manual-reference-pages';
import {
  appendSchemaTab,
  referenceDeclaration,
  referenceSourceTitle,
  schemaReferenceTypes,
  splitReferenceSections,
} from './merged-reference';
import type { ApiReferenceLanguage } from './tex';

/** 既有精选成员表仍为手写说明；类型定义和 Schema 位置来自当前公开源码 */
export const createManualReferenceMdx = (
  membersSource: string,
  schemasSource: string,
  page: (typeof manualReferencePages)[number],
  lang: ApiReferenceLanguage,
): string => {
  const schemaSections = new Map<string, string>();
  const supplements: Array<string> = [];
  for (const section of splitReferenceSections(schemasSource)) {
    const names = [...section.body.matchAll(/<ZodSchema\b[\s\S]*?name="(\w+)"/gu)].map(match => match[1]);
    if (names.length === 1) {
      if (schemaSections.has(names[0])) throw new Error(`Repeated manual Schema: ${page.owner}#${names[0]}`);
      schemaSections.set(names[0], section.body);
    } else if (section.body) supplements.push(section.name ? `**${section.name}**\n\n${section.body}` : section.body);
  }
  const sections = splitReferenceSections(membersSource, '3,4');
  const introduction = sections.find(section => !section.name)?.body ?? '';
  let units = sections.filter(section => section.name);
  if (!units.length && membersSource.trim() && page.members.length)
    units = [{ name: page.members.join(' / '), body: membersSource.trim() }];
  const output: Array<string> = [];
  for (const unit of units) {
    const names = unit.name.split(' / ');
    let body = unit.body;
    const schemaName = page.pairs[unit.name];
    const derived = schemaName ? schemaReferenceTypes(schemaName, page.hints) : [];
    const titles = [...names, ...derived.map(item => item.name)].filter(
      (name, index, all) => all.indexOf(name) === index,
    );
    const definitions = (derived.length ? derived : names.map(name => referenceDeclaration(name, page.hints))).filter(
      item => /^(?:export )?(?:type|interface) /u.test(item.text),
    );
    if (definitions.length) {
      body = `<DocTabs defaultValue="members">\n\n<DocTab value="members" label="${lang === 'zh' ? '属性' : 'Members'}">\n\n${body}\n\n</DocTab>\n\n<DocTab value="definition" label="${lang === 'zh' ? '类型定义' : 'Type definition'}">\n\n\`\`\`ts\n${definitions.map(item => item.text).join('\n\n')}\n\`\`\`\n\n</DocTab>\n\n</DocTabs>`;
    }
    if (schemaName) {
      const schema = schemaSections.get(schemaName);
      if (!schema) throw new Error(`Missing manual Schema pair: ${page.owner}#${schemaName}`);
      schemaSections.delete(schemaName);
      titles.push(schemaName);
      body = appendSchemaTab(body, schema, lang);
    }
    output.push(`#### ${titles.map(name => referenceSourceTitle(name, page.hints)).join(' / ')}\n\n${body}`);
  }
  for (const [name, schema] of schemaSections) {
    const types = schemaReferenceTypes(name, page.hints);
    const title = [...types.map(item => item.name), name]
      .map(item => referenceSourceTitle(item, page.hints))
      .join(' / ');
    const definition = types.length ? `\`\`\`ts\n${types.map(item => item.text).join('\n\n')}\n\`\`\`` : '';
    output.push(`#### ${title}\n\n${definition ? appendSchemaTab(definition, schema, lang) : schema}`);
  }
  const preamble = units[0]?.body === introduction ? '' : introduction;
  const heading = page.embedded ? `**${page.title[lang]}**` : `## ${page.title[lang]}`;
  return [preamble, ...supplements, heading, ...output].filter(Boolean).join('\n\n');
};

/** 重新生成手写精选表与源码类型 / Schema 的合并视图 */
export const writeManualReferences = (contents: string): void => {
  for (const page of manualReferencePages) {
    const directory = path.join(contents, page.owner, '_includes');
    mkdirSync(directory, { recursive: true });
    for (const lang of ['zh', 'en'] as const) {
      const members = readFileSync(path.join(directory, `members.${lang}.mdx`), 'utf8');
      const schemas = readFileSync(path.join(directory, `schemas.${lang}.mdx`), 'utf8');
      writeFileSync(
        path.join(directory, `generated.${lang}.mdx`),
        `{/* Generated by pnpm generate:api-reference. Do not edit manually. */}\n\n${createManualReferenceMdx(members, schemas, page, lang)}\n`,
        'utf8',
      );
    }
  }
};
