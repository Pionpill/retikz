import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { createMergedReferenceMdx } from './merged-reference';
import { assertPlotGuideTranslated, translatePlotGuide } from './plot-guide.en';
import { createApiReferenceMdx } from './tex';
import type { ApiReferencePackageConfig } from './tex';

const root = path.resolve(import.meta.dirname, '../../../..');

/** 从公开声明生成辅助组件参考，复用辅助契约的 Schema 说明 */
export const writePlotGuideApiReferenceMdx = async (): Promise<void> => {
  for (const kind of ['axis', 'legend'] as const) {
    const name = kind === 'axis' ? 'Axis' : 'Legend';
    const owner = `viz/plot/guide/${kind}`;
    const config: ApiReferencePackageConfig = {
      packageName: '@retikz/plot-react',
      packageDirectory: 'packages/viz/plot-react',
      tsconfigPath: path.join(root, 'packages/viz/plot-react/tsconfig.json'),
      translate: translatePlotGuide,
      entries: [
        {
          source: path.join(root, 'packages/viz/plot-react/src/index.ts'),
          title: { zh: '声明属性', en: 'Declaration properties' },
          symbols: [`Plot${name}Props`],
        },
      ],
    };
    const contents = path.join(root, 'apps/docs/src/modules/docs/contents');
    const output = path.join(contents, owner, '_includes');
    mkdirSync(output, { recursive: true });
    for (const lang of ['zh', 'en'] as const) {
      const props = await createApiReferenceMdx(config, lang);
      const ir = await createApiReferenceMdx(
        {
          packageName: '@retikz/plot',
          packageDirectory: 'packages/viz/plot',
          tsconfigPath: path.join(root, 'packages/viz/plot/tsconfig.json'),
          translate: translatePlotGuide,
          entries: [
            {
              source: path.join(root, 'packages/viz/plot/src/index.ts'),
              title: { zh: 'Source IR', en: 'Source IR' },
              symbols: [`IRPlot${name}Guide`],
              declarationOnlySymbols: [`IRPlot${name}Guide`],
            },
          ],
        },
        lang,
      );
      const source = `${props}\n\n${ir}`;
      if (lang === 'en') assertPlotGuideTranslated();
      const schemas = readFileSync(path.join(contents, owner, `_includes/schemas.${lang}.mdx`), 'utf8');
      const merged = createMergedReferenceMdx(source, schemas, owner, lang, true);
      writeFileSync(
        path.join(output, `generated.${lang}.mdx`),
        `{/* Generated by scripts/generate-plot-guide-api-reference.ts. Do not edit manually. */}\n\n${merged}\n`,
        'utf8',
      );
    }
  }
};
