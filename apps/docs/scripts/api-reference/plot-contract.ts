import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { createMergedReferenceMdx } from './merged-reference';

/** 将 Plot 共享配置投影到各自的唯一参考入口 */
export const writePlotContractApiReferenceMdx = (): void => {
  const contents = path.resolve(import.meta.dirname, '../../src/modules/docs/contents');
  for (const topic of ['mark', 'guide']) {
    const owner = `viz/plot/${topic}`;
    const directory = path.join(contents, owner, '_includes');
    mkdirSync(directory, { recursive: true });
    for (const lang of ['zh', 'en'] as const) {
      const schemas = readFileSync(path.join(directory, `schemas.${lang}.mdx`), 'utf8');
      const merged = createMergedReferenceMdx('', schemas, owner, lang, true);
      writeFileSync(
        path.join(directory, `generated.${lang}.mdx`),
        `{/* Generated by scripts/generate-plot-contract-api-reference.ts. Do not edit manually. */}\n\n${merged}\n`,
        'utf8',
      );
    }
  }
};
